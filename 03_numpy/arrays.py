# NumPy Arrays
import numpy as np

numbers = np.array([10, 20, 30, 40, 50])

print("Array:", numbers)
print("First element:", numbers[0])
print("Last element:", numbers[-1])

print("Mean:", np.mean(numbers))
print("Maximum:", np.max(numbers))
print("Minimum:", np.min(numbers))
print("Sum:", np.sum(numbers))
